def calculator():
    print(logo)
    should_accumulate = True
    f_number = float(input("What's the first number?: "))

    while should_accumulate:

        for k in operations:
            print(k)
        op = input("Pick an operation: ")
        s_number = float(input("What's the next number?: "))

        answer = operations[op](f_number, s_number)
        print(f"{f_number} {op} {s_number} = {answer}")

        again = input(f"Type 'y' to continue calculating with {answer}, or type 'n' to start a new calculation: ").lower()
        if  again == "y":
            f_number = answer
        else:
            should_accumulate = False
            print("\n" * 20)
            calculator()

calculator()